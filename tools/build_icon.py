"""Generate icon and branded Inno Setup bitmap assets."""
from pathlib import Path
from PIL import Image, ImageDraw
out=Path('assets');out.mkdir(exist_ok=True)
im=Image.new('RGBA',(768,768))
d=ImageDraw.Draw(im)
def box(coords):return tuple(v*3 for v in coords)
d.rounded_rectangle(box((12,12,244,244)),radius=165,fill='#303943')
d.rounded_rectangle(box((42,55,118,116)),radius=39,fill='#E4A83C')
d.rounded_rectangle(box((42,78,214,201)),radius=48,fill='#E4A83C')
d.rounded_rectangle(box((42,86,214,201)),radius=48,fill='#FFD16C')
d.ellipse(box((89,104,167,182)),fill='#286FBD')
d.line(box((112,158,144,126)),fill='#F8FAFC',width=30)
for x,y in [(112,158),(144,126)]:d.ellipse(box((x-5,y-5,x+5,y+5)),fill='#F8FAFC')
d.ellipse(box((144,159,158,173)),fill='#6EE0AD')
im=im.resize((256,256),Image.Resampling.LANCZOS)
im.save(out/'folder.ico',sizes=[(16,16),(24,24),(32,32),(48,48),(64,64),(128,128),(256,256)])
im.save(out/'folder.png')
banner=Image.new('RGB',(164,314));p=ImageDraw.Draw(banner)
for y in range(314):
    t=y/313;p.line((0,y,164,y),fill=(int(30+12*t),int(47+45*t),int(68+72*t)))
p.ellipse((-85,190,210,485),fill='#286FBD')
p.ellipse((94,-72,244,78),fill='#54A987')
logo=im.resize((120,120),Image.Resampling.LANCZOS)
banner.paste(logo,(22,77),logo)
banner.save(out/'wizard.bmp')
small=Image.new('RGB',(55,55),'#F4F7FB')
logo=im.resize((49,49),Image.Resampling.LANCZOS)
small.paste(logo,(3,3),logo);small.save(out/'wizard-small.bmp')
